#!/usr/bin/env python3
"""Pins and rewrites the third-party downloads of HRX for the Nix build.

HRX resolves its dependencies at CMake configure time from two pinned
sources: MODULE.cmake.lock (archives and single files, with SHA256 hashes) and
Loom's AMDGPU ISA XML archive descriptor. The Nix sandbox has no network, so
every pinned download is a `fetchurl` in hrx-deps.nix, and `rewrite` points the
source tree at those store paths with file:// URLs. HRX's own hash checks and
dependency patches still run on the local copies.

Usage:
  hrx-deps.py generate <hrx-source> [<out.nix>]   # after changing the HRX pin
  hrx-deps.py rewrite <hrx-source> <map.json>     # in the build (loom-runtime.nix)
"""

import json
import os
import re
import sys

LOCK = "MODULE.cmake.lock"
ARCHIVE_DESCRIPTORS = ["loom/build_tools/amdgpu/isa_xml/archive.bzl"]
FILES = [LOCK] + ARCHIVE_DESCRIPTORS


def pinned_downloads(source):
    """Returns [(name, sha256, [urls])] for every pinned download."""
    downloads = []
    with open(os.path.join(source, LOCK), encoding="utf-8") as lock:
        text = lock.read()
    hashes = dict(re.findall(r'set\(IREE_DEP_(\w+)_SHA256 "([0-9a-f]{64})"\)', text))
    for name, block in re.findall(r"set\(IREE_DEP_(\w+)_URLS\n(.*?)\)", text, re.S):
        urls = re.findall(r'"([^"]+)"', block)
        if urls and name in hashes:
            downloads.append((name.lower(), hashes[name], urls))
    for descriptor in ARCHIVE_DESCRIPTORS:
        with open(os.path.join(source, descriptor), encoding="utf-8") as f:
            text = f.read()
        sha256 = re.search(r'"sha256": "([0-9a-f]{64})"', text).group(1)
        urls = re.findall(r'"(https://[^"]+)"', text)
        downloads.append(("amdgpu_isa_xml", sha256, urls))
    return downloads


def store_name(url):
    # Keep the URL's file name so CMake recognizes the archive type.
    base = url.split("?")[0].rstrip("/").split("/")[-1] or "file"
    return re.sub(r"[^A-Za-z0-9+._?=-]", "_", base).lstrip(".")


def generate(source, out):
    lines = [
        "# Generated by `hrx-deps.py generate` from HRX's MODULE.cmake.lock and Loom's",
        "# ISA XML descriptor. Do not edit; regenerate when the HRX pin changes.",
        "{ fetchurl }:",
        "[",
    ]
    for name, sha256, urls in pinned_downloads(source):
        lines += [
            "  rec {",
            f'    id = "{name}";',
            "    urls = [",
            *[f'      "{url}"' for url in urls],
            "    ];",
            "    file = fetchurl {",
            f'      name = "{store_name(urls[0])}";',
            "      inherit urls;",
            f'      sha256 = "{sha256}";',
            "    };",
            "  }",
        ]
    lines.append("]")
    text = "\n".join(lines) + "\n"
    if out:
        with open(out, "w", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


def rewrite(source, mapping):
    """Replaces every pinned URL with its file:// store path from mapping."""
    with open(mapping, encoding="utf-8") as f:
        replacements = {url: "file://" + path for url, path in json.load(f).items()}
    for _, _, urls in pinned_downloads(source):
        missing = [url for url in urls if url not in replacements]
        if missing:
            sys.exit(f"hrx-deps.nix is stale, no pin for {missing[0]}: run hrx-deps.py generate")
    for relative in FILES:
        path = os.path.join(source, relative)
        with open(path, encoding="utf-8") as f:
            text = f.read()
        for url, local in replacements.items():
            text = text.replace(f'"{url}"', f'"{local}"')
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


if __name__ == "__main__":
    command, source = sys.argv[1:3]
    if command == "generate":
        generate(source, sys.argv[3] if len(sys.argv) > 3 else None)
    elif command == "rewrite":
        rewrite(source, sys.argv[3])
    else:
        sys.exit(__doc__)
